export function getWeightedRandomBird(): Bird {
  const r = Math.random();
  let rarity: string;
  if (r < 0.60) {
    rarity = "common";
  } else if (r < 0.85) {
    rarity = "uncommon";
  } else if (r < 0.97) {
    rarity = "rare";
  } else {
    rarity = "legendary";
  }
  const pool = birds.filter((b) => b.rarity === rarity);
  return pool[Math.floor(Math.random() * pool.length)];
}

