NUM_CLASSES = 296
WEIGHTS_PATH = ROOT / "tf_cache" / "best_weights_continue.weights.h5"
BATCH_SIZE = 32                    # internal Keras batch size
CHUNK_IMAGES_PER_FOLDER = 64       # process this many images' TTA variants per predict call
                                   # -> 64 * 3 = 192 variants, batched 32-at-a-time by Keras

AUDIT_OUT.mkdir(parents=True, exist_ok=True)
