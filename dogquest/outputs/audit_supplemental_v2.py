# Tier-A thresholds
DIFFERENT_BREED_THRESHOLD = 0.40   # top-1 prediction confidence floor for "high conf"
OWN_CLUSTER_LOW_THRESHOLD = 0.05   # truth-cluster confidence ceiling for "low own"
MIN_KEEP_PER_FOLDER = 50           # never quarantine if it would leave < this many
