"""
audit_supplemental_v2.py — Tier-A label-noise auditor for supplemental_dogs/.

Flags images where the model is high-confidence-wrong about the labeled breed,
moves them (recoverable) to supplemental_dogs_quarantine_v2/<folder>/<file>.

Cluster-aware: same-cluster predictions never flag (e.g. an image in
working_kelpie/ predicted as "Australian Kelpie" is fine because they are
in the same synonym cluster).

Usage:
    python outputs/audit_supplemental_v2.py baseline              # measure baseline (no moves)
    python outputs/audit_supplemental_v2.py sanity --folder akita # audit one folder, no moves
    python outputs/audit_supplemental_v2.py audit                 # full sweep (executes moves)
    python outputs/audit_supplemental_v2.py audit --folder akita  # one folder + execute
    python outputs/audit_supplemental_v2.py post                  # post-audit measurement + decision
    python outputs/audit_supplemental_v2.py rollback              # restore all quarantined files
    python outputs/audit_supplemental_v2.py status                # print manifest summary

Outputs in outputs/audit_v2/:
    baseline_metrics.json   — 3-seed baseline metrics (top-1, top-3, rejected)
    post_metrics.json       — same shape, after audit
    quarantine_manifest.jsonl — append-only record of all moved files
    audit_progress.json     — live progress during full sweep
    per_folder_stats.json   — per-folder breakdown
    REPORT.md / SUCCESS.md / REGRESSION.md / MARGINAL.md — generated by `post`
"""
