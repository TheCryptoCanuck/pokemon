def cmd_baseline(args):
    model = load_model()
    labels, label_to_idx, dogs, dog_index = load_assets()
    print(f"Measuring baseline (3 seeds: {SEEDS_FOR_HARNESS})...")
    results = measure_baseline(model, labels, dogs, dog_index)
    avg = average_metrics(results)
    payload = {
        "measured_at": datetime.utcnow().isoformat() + "Z",
        "seeds": SEEDS_FOR_HARNESS,
        "per_seed": results,
        "average": avg,
    }
    BASELINE_PATH.write_text(json.dumps(payload, indent=2, default=str), encoding="utf-8")
    print(f"\nBaseline written: avg top-1 = {avg['top1_pct']:.1f}%, avg top-3 = {avg['top3_pct']:.1f}%")
    print(f"Saved to: {BASELINE_PATH}")


def cmd_sanity(args):
    """One-folder dry run, prints the flags but does NOT move files."""
    model = load_model()
    labels, label_to_idx, dogs, dog_index = load_assets()
    folder_path = t.SUPPLEMENTAL_DIR / args.folder
    if not folder_path.exists():
        print(f"ERROR: folder {folder_path} does not exist.")
        sys.exit(2)
    quarantined = already_quarantined()
    print(f"Sanity audit on {folder_path.name}/ (dry-run, no moves)...")
    t0 = time.time()
    res = audit_folder(model, labels, label_to_idx, dog_index,
                       folder_path, dry_run=True, quarantined_set=quarantined)
    dt = time.time() - t0
    print(f"\nFolder: {res['folder']}")
    print(f"  truth_cluster: {res.get('truth_cluster', 'N/A')}")
    print(f"  total images: {res['n']}, audited: {res['n_audited']}, "
          f"already_quarantined: {res.get('n_skipped_already_quarantined', 0)}")
    print(f"  flagged (after MIN_KEEP={MIN_KEEP_PER_FOLDER}): {res['n_flagged']}")
    print(f"  inference time: {dt:.1f}s ({dt/max(1, res['n_audited'])*1000:.0f}ms/img)")
    if res["flags"]:
        print(f"\nFirst {min(10, len(res['flags']))} flagged:")
        for f in res["flags"][:10]:
            print(f"    {Path(f['src']).name}: predicted '{f['top_cluster']}' @ {f['top_conf']:.1%}, "
                  f"own-cluster conf {f['own_conf']:.1%}")
    return res


def cmd_audit(args):
    """Full sweep (or single folder if --folder set). Executes moves."""
    model = load_model()
    labels, label_to_idx, dogs, dog_index = load_assets()
    quarantined = already_quarantined()

    if args.folder:
        folders = [t.SUPPLEMENTAL_DIR / args.folder]
        if not folders[0].exists():
            print(f"ERROR: folder {folders[0]} does not exist.")
            sys.exit(2)
    else:
        folders = list_audit_folders(t.SUPPLEMENTAL_DIR, dog_index)

    print(f"Auditing {len(folders)} folder(s); already-quarantined entries: {len(quarantined)}")
    per_folder = []
    total_flagged = 0
    t0 = time.time()
    for i, fp in enumerate(folders, 1):
        res = audit_folder(model, labels, label_to_idx, dog_index,
                           fp, dry_run=False, quarantined_set=quarantined)
        per_folder.append(res)
        total_flagged += res["n_flagged"]
        elapsed = time.time() - t0
        remaining = elapsed / i * (len(folders) - i)
        write_progress({
            "started": datetime.utcnow().isoformat() + "Z",
            "folders_total": len(folders),
            "folders_done": i,
            "current_folder": fp.name,
            "total_flagged_so_far": total_flagged,
            "elapsed_sec": elapsed,
            "eta_sec": remaining,
        })
        print(f"[{i:3}/{len(folders)}] {fp.name}: audited={res['n_audited']}, "
              f"flagged={res['n_flagged']} (running total: {total_flagged}) "
              f"[{elapsed/60:.1f}m elapsed, ETA {remaining/60:.1f}m]")

    PER_FOLDER_PATH.write_text(json.dumps(per_folder, indent=2, default=str), encoding="utf-8")
    print(f"\nAudit complete. Total flagged: {total_flagged}. Per-folder stats: {PER_FOLDER_PATH}")
    return per_folder


def cmd_post(args):
    """Re-measure with 3-seed harness, compare to baseline, write decision doc."""
    if not BASELINE_PATH.exists():
        print(f"ERROR: {BASELINE_PATH} not found. Run `baseline` first.")
        sys.exit(2)
    baseline = json.loads(BASELINE_PATH.read_text(encoding="utf-8"))

    model = load_model()
    labels, label_to_idx, dogs, dog_index = load_assets()
    print(f"Measuring post-audit metrics (3 seeds: {SEEDS_FOR_HARNESS})...")
    results = measure_baseline(model, labels, dogs, dog_index)
    avg_post = average_metrics(results)
    payload = {
        "measured_at": datetime.utcnow().isoformat() + "Z",
        "seeds": SEEDS_FOR_HARNESS,
        "per_seed": results,
        "average": avg_post,
    }
    POST_PATH.write_text(json.dumps(payload, indent=2, default=str), encoding="utf-8")

    avg_pre = baseline["average"]
    delta_top1 = avg_post["top1_pct"] - avg_pre["top1_pct"]
    delta_top3 = avg_post["top3_pct"] - avg_pre["top3_pct"]
    print(f"\nBaseline:  top-1={avg_pre['top1_pct']:.1f}%  top-3={avg_pre['top3_pct']:.1f}%")
    print(f"Post:      top-1={avg_post['top1_pct']:.1f}%  top-3={avg_post['top3_pct']:.1f}%")
    print(f"Delta:     top-1={delta_top1:+.1f}pt  top-3={delta_top3:+.1f}pt")

    # Decision rule per task spec
    if delta_top1 >= -1.0:
        decision = "KEEP_SUCCESS"
        doc = AUDIT_OUT / "SUCCESS.md"
    elif delta_top1 < -2.0:
        decision = "ROLLBACK_REGRESSION"
        doc = AUDIT_OUT / "REGRESSION.md"
    else:
        decision = "KEEP_MARGINAL"
        doc = AUDIT_OUT / "MARGINAL.md"

    write_decision_doc(doc, decision, avg_pre, avg_post, baseline, payload)
    print(f"\nDecision: {decision}")
    print(f"Doc: {doc}")

    if decision == "ROLLBACK_REGRESSION":
        print("\nAuto-rollback engaged...")
        n = rollback_all()
        print(f"Restored {n} files.")

    return decision


def write_decision_doc(path: Path, decision: str, pre: dict, post: dict, base_payload: dict, post_payload: dict):
    delta1 = post["top1_pct"] - pre["top1_pct"]
    delta3 = post["top3_pct"] - pre["top3_pct"]
    title = {
        "KEEP_SUCCESS": "Audit v2 — SUCCESS (quarantine kept)",
        "ROLLBACK_REGRESSION": "Audit v2 — REGRESSION (auto-rollback engaged)",
        "KEEP_MARGINAL": "Audit v2 — MARGINAL (quarantine kept, flagged for review)",
    }[decision]
    lines = [
        f"# {title}",
        "",
        f"**Decision:** `{decision}`  ",
        f"**Baseline measured:** {base_payload['measured_at']}  ",
        f"**Post measured:** {post_payload['measured_at']}  ",
        f"**Seeds:** {SEEDS_FOR_HARNESS}",
        "",
        "## Headline",
        "",
        "| Metric | Baseline | Post | Delta |",
        "|---|---|---|---|",
        f"| Avg top-1 | {pre['top1_pct']:.2f}% | {post['top1_pct']:.2f}% | {delta1:+.2f}pt |",
        f"| Avg top-3 | {pre['top3_pct']:.2f}% | {post['top3_pct']:.2f}% | {delta3:+.2f}pt |",
        "",
        "## Per-seed",
        "",
        "| Seed | Baseline top-1 | Post top-1 | Δ | Baseline top-3 | Post top-3 | Δ |",
        "|---|---|---|---|---|---|---|",
    ]
    pre_seeds = {r["seed"]: r for r in base_payload["per_seed"]}
    post_seeds = {r["seed"]: r for r in post_payload["per_seed"]}
    for s in SEEDS_FOR_HARNESS:
        b, p = pre_seeds.get(s, {}), post_seeds.get(s, {})
        lines.append(
            f"| {s} | {b.get('top1_pct',0):.1f}% | {p.get('top1_pct',0):.1f}% | "
            f"{(p.get('top1_pct',0)-b.get('top1_pct',0)):+.1f}pt | "
            f"{b.get('top3_pct',0):.1f}% | {p.get('top3_pct',0):.1f}% | "
            f"{(p.get('top3_pct',0)-b.get('top3_pct',0)):+.1f}pt |"
        )
    lines += [
        "",
        "## Decision rule",
        "",
        f"- top-1 Δ ≥ −1.0 pt → KEEP_SUCCESS",
        f"- top-1 Δ < −2.0 pt → ROLLBACK_REGRESSION (auto)",
        f"- otherwise → KEEP_MARGINAL (flag for human review)",
        "",
        f"This run's top-1 Δ = {delta1:+.2f}pt → **{decision}**",
        "",
        "## Rollback hint",
        "",
        "```",
        "python outputs/audit_supplemental_v2.py rollback",
        "```",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def cmd_status(args):
    if not MANIFEST_PATH.exists():
        print("No manifest yet.")
        return
    by_folder = {}
    n_total = 0
    for line in MANIFEST_PATH.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            rec = json.loads(line)
        except Exception:
            continue
        n_total += 1
        by_folder.setdefault(rec["folder"], 0)
        by_folder[rec["folder"]] += 1
    print(f"Quarantine manifest: {n_total} files across {len(by_folder)} folders")
    for folder, n in sorted(by_folder.items(), key=lambda kv: -kv[1])[:20]:
        print(f"  {n:4}  {folder}")


